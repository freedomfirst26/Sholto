        effect.SetParam(DeckEffect.MixParamId, 1.0);
        Run(effect, Secs(0.1), LongBlock, sink, ref cursor);

        effect.RequestReset();                                   // fade reaches 0 mid-buffer
        SetDsp(effect);
        Run(effect, Secs(0.1), LongBlock, sink, ref cursor);

        if (index == FilterIndex) AssertFilterSamples(((EveryNth)sink).Samples);
        else Assert.True(Expected[index] == hash.Value, $"actual 0x{hash.Value:X16}");
    }

    private static void SetDsp(DeckEffect effect)
    {
        switch (effect.EffectId)
        {
            case "echo":
            case "roll": effect.SetParam(0, 1); break;
            case "eq3": effect.SetParam(0, 0); break;
            case "filter": effect.SetParam(0, 0.1); break;
            default: Assert.Fail($"unknown effect {effect.EffectId}"); break;
        }
    }

    private static int Secs(double s) => (int)(s * Rate);

    private static float Tone(int frame) => 0.5f * MathF.Sin(2f * MathF.PI * 440f * frame / Rate);

    private static void Run(DeckEffect effect, int frames, int block, IOutputSink sink, ref int cursor)
    {
        var buf = new float[block * 2];
        int done = 0;
        while (done < frames)
        {
            int n = Math.Min(block, frames - done);
            var span = buf.AsSpan(0, n * 2);
            for (int i = 0; i < n; i++)
            {
                float s = Tone(cursor + done + i);
                span[i * 2] = s; span[i * 2 + 1] = s;
            }
            effect.Process(span, 2);
            for (int i = 0; i < span.Length; i++) sink.Add(span[i]);
            done += n;
        }
        cursor += frames;
    }

    private static void AssertFilterSamples(List<float> actual)
    {
        Assert.Equal(ExpectedFilterSamples.Length, actual.Count);
        int worst = 0;
        for (int i = 1; i < actual.Count; i++)
            if (!(Math.Abs(actual[i] - ExpectedFilterSamples[i]) <= Math.Abs(actual[worst] - ExpectedFilterSamples[worst]))) worst = i;
        float dev = Math.Abs(actual[worst] - ExpectedFilterSamples[worst]);
        Assert.True(dev <= LibmFilterTolerance,
            $"filter output sample {worst} (output float {worst * FilterSampleStride}) is {actual[worst]:G9}, " +
            $"expected {ExpectedFilterSamples[worst]:G9}: |deviation| {dev:G9} > {LibmFilterTolerance:G9}");
    }

    private interface IOutputSink
    {
        void Add(float sample);
    }

    private sealed class EveryNth(int stride) : IOutputSink
    {
        private readonly int _stride = stride;
        private int _index;

        public List<float> Samples { get; } = [];

        public void Add(float sample)
        {
            if (_index++ % _stride == 0) Samples.Add(sample);
        }
    }

    private sealed class Fnv : IOutputSink
    {
        public ulong Value { get; private set; } = 14695981039346656037UL;

        public void Add(float sample)
        {
            int v = BitConverter.SingleToInt32Bits(sample);
            for (int b = 0; b < 4; b++)
            {
                Value ^= (byte)(v >> (8 * b));
                Value *= 1099511628211UL;
            }
        }
    }
